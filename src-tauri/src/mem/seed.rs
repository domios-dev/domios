//! Seed bundled starter mem_items on first install. Idempotent via marker file.
//! Phase 3.2 will swap these placeholders for include_str! of bundled SKILL.md
//! files. For now we ship the minimum that makes wake-up + bridge rule sane:
//! - preference_identity placeholder
//! - 3 baseline rules
//! - codeterm skill stub pointing at the embedded BRIDGE_MEM payload

use super::{MemKind, MemScope, NewMemItem, MemManager};

const SEED_MARKER: &str = ".bundled-seeded-v1";

pub fn seed_bundled(mem: &MemManager) -> Result<usize, String> {
    let marker = mem.db_path().parent().unwrap_or(std::path::Path::new(".")).join(SEED_MARKER);
    if marker.exists() {
        return Ok(0);
    }

    let items: Vec<NewMemItem> = vec![
        NewMemItem {
            kind: MemKind::Preference,
            scope: MemScope::Global,
            title: "identity".into(),
            summary: Some("Agent identity placeholder — overwrite via mem save".into()),
            area: None,
            tags: vec!["bundled".into(), "identity".into()],
            body: "No identity configured yet. Replace this row by running:\n  codeterm mem save --kind preference --title identity \"I am <name>, ...\"".into(),
            source: Some("bundled:v1".into()),
            importance: 5.0,
        },
        NewMemItem {
            kind: MemKind::Rule,
            scope: MemScope::Global,
            title: "never edit autogen files".into(),
            summary: Some("CLAUDE.md / AGENTS.md / AGENT.md are auto-regenerated".into()),
            area: None,
            tags: vec!["bundled".into(), "autogen".into()],
            body: "Never edit CLAUDE.md, AGENTS.md, or AGENT.md — they are auto-regenerated by CodeTerm on every start. To persist context, use `codeterm mem save` instead.".into(),
            source: Some("bundled:v1".into()),
            importance: 5.0,
        },
        NewMemItem {
            kind: MemKind::Rule,
            scope: MemScope::Global,
            title: "save to mem not provider memory".into(),
            summary: Some("Persistent memory lives in mem only".into()),
            area: None,
            tags: vec!["bundled".into(), "memory".into()],
            body: "Persistent memory lives in CodeTerm mem, not in `~/.claude/projects/*/memory/` or any provider-specific auto-memory. Those vanish on provider switch. Every `codeterm mem save` survives restarts and provider switches.".into(),
            source: Some("bundled:v1".into()),
            importance: 5.0,
        },
        NewMemItem {
            kind: MemKind::Rule,
            scope: MemScope::Global,
            title: "search before asking".into(),
            summary: Some("Query mem before asking the user".into()),
            area: None,
            tags: vec!["bundled".into(), "workflow".into()],
            body: "Before asking the user a question they might already have answered, run `codeterm mem search` first. The user may have installed skills, saved facts, or recorded preferences you don't know about yet.".into(),
            source: Some("bundled:v1".into()),
            importance: 5.0,
        },
        NewMemItem {
            kind: MemKind::Skill,
            scope: MemScope::Global,
            title: "codeterm".into(),
            summary: Some("CodeTerm CLI skill — pane / workspace / agent / mem control".into()),
            area: Some("codeterm".into()),
            tags: vec!["bundled".into(), "core".into(), "cli".into()],
            body: "## CodeTerm CLI\n\nUse `codeterm` to control panes, workspaces, agents, mesh peers, and mem.\n\n- `codeterm pane list` — list panes\n- `codeterm send-text \"...\" --pane ID` — type into a pane\n- `codeterm agent spawn claude --task \"...\" --role Worker --parent $CODETERM_PANE_ID` — spawn a worker\n- `codeterm mesh peers` — list mesh peers\n- `codeterm mem search/get/save/recall/wake-up` — unified memory\n\nAlways use the CLI from inside CodeTerm via Bash. Do not curl the REST API directly.".into(),
            source: Some("bundled:v1".into()),
            importance: 4.0,
        },
    ];

    let mut count = 0;
    for item in items {
        if mem.save(item).is_ok() {
            count += 1;
        }
    }

    let _ = std::fs::write(&marker, b"v1\n");
    Ok(count)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn seed_runs_once() {
        let mem = MemManager::open_in_memory().unwrap();
        // The in-memory DB sets db_path to a tmp dir without marker
        let n1 = seed_bundled(&mem).unwrap();
        assert!(n1 >= 5, "expected ≥5 seeded items, got {}", n1);
        // Re-running should be a no-op (marker file written)
        let n2 = seed_bundled(&mem).unwrap();
        assert_eq!(n2, 0, "second seed should be no-op");
    }

    #[test]
    fn seeded_identity_appears_in_wake_up() {
        let mem = MemManager::open_in_memory().unwrap();
        seed_bundled(&mem).unwrap();
        let out = mem.wake_up(&super::super::WakeUpOptions::default()).unwrap();
        assert!(out.contains("L0 — Identity"));
        assert!(out.contains("L1 — Critical context"));
        assert!(out.contains("never edit autogen") || out.contains("Rules"));
    }
}
