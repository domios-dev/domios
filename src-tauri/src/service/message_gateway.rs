//! MessageGateway — the single submission seam for outbound tab traffic.
//!
//! PHASE 1 is a PARITY WRAPPER: it classifies, dedups, and forwards to the
//! existing delivery paths (`Messenger::deliver`, `send_text`,
//! `send_text_batch`, the ordered key-write path) with zero behavior change.
//! No caller is migrated yet — the wrapper only adds a typed seam + idempotency.

use std::collections::{HashMap, HashSet, VecDeque};

use parking_lot::Mutex;

use super::messenger::{Delivery, MessageEnvelope, Messenger};
use super::pty_io::{
    await_action_deadline, execute_ordered_actions, OrderedPtyAction, SendBatchItem,
};

/// Default bound for the idempotency cache (entries, no persistence).
pub const IDEMPOTENCY_CAPACITY: usize = 512;

/// Delivery semantics owned by the gateway. PHASE 1 carries the class as
/// metadata only — it does not yet alter routing (parity is preserved).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum DeliveryClass {
    /// A human-authored turn: the user's own prompt entering a tab.
    UserTurn,
    /// Machine-authored traffic between agents (reports, cross-tab, mesh relays).
    AgentTraffic,
    /// A CodeTerm-originated notice or reminder injected into a tab.
    SystemNotice,
    /// Uninterpreted key/control bytes written straight to the PTY.
    RawKeys,
}

/// Where a submission entered the system — used for idempotency scoping.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MessageOrigin {
    /// Submitted by another local tab in this instance.
    LocalTab,
    /// Arrived from a mesh peer over the flat peer network.
    MeshPeer,
    /// Presented a service token (external HTTP/CLI caller).
    ServiceToken,
    /// Issued by the local UI (a frontend action).
    Ui,
    /// Generated by CodeTerm itself (onboarding, reminders, notices).
    System,
}

/// A single ordered key action, mirroring the existing HTTP action vocabulary.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum KeyStroke {
    Key(String),
    Delay(u64),
}

/// The payload of an outbound submission.
#[derive(Debug, Clone)]
pub enum MessageBody {
    /// Plain or enveloped text. Text messages always submit.
    Text { body: String },
    /// A text prefix followed by ordered key actions (arrows, ctrl-keys, delays).
    Keys {
        text: String,
        strokes: Vec<KeyStroke>,
    },
    /// A staged multi-item batch send.
    Batch(Vec<SendBatchItem>),
}

/// One submission through the gateway.
#[derive(Debug, Clone)]
pub struct OutboundMessage {
    pub target: String,
    pub body: MessageBody,
    pub envelope: Option<MessageEnvelope>,
    pub class: DeliveryClass,
    pub origin: MessageOrigin,
    pub idempotency_key: Option<String>,
}

/// Result of a successful submission.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DeliveryReceipt {
    /// The underlying delivery record when the path produces one (enveloped
    /// PTY/chat); `None` for plain text / keys / batch, which return unit today.
    pub delivery: Option<Delivery>,
    /// True when this receipt was replayed from the idempotency cache.
    pub dedup_hit: bool,
    /// Echoes the submitted idempotency key when one was provided.
    pub idempotency_key: Option<String>,
}

/// Typed delivery failure. Adapter-friendly for the upstream taxonomy (BLACKSTAR
/// task_7fei9d owns final naming); `DeliveredUnverified` and `TabNotFound` are
/// deliberately distinct so callers can retry-vs-abort correctly.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum DeliveryError {
    /// The target tab could not be resolved to a live tab/PTY.
    TabNotFound { target: String },
    /// Bytes were written but submission could not be confirmed.
    DeliveredUnverified { detail: String },
    /// Any other failure from the underlying path, kept opaque for adapters.
    Transport { detail: String },
}

impl std::fmt::Display for DeliveryError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            Self::TabNotFound { target } => write!(f, "Tab not found: {target}"),
            Self::DeliveredUnverified { detail } => write!(f, "delivered unverified: {detail}"),
            Self::Transport { detail } => write!(f, "transport error: {detail}"),
        }
    }
}

impl std::error::Error for DeliveryError {}

/// The underlying delivery paths the gateway wraps. `ServiceContext` implements
/// this by forwarding verbatim; tests implement a recording fake.
pub trait DeliverySeam {
    fn deliver_enveloped(
        &self,
        to_tab: &str,
        envelope: MessageEnvelope,
        body: &str,
    ) -> Result<Delivery, String>;
    fn deliver_text(&self, tab: &str, text: &str) -> Result<(), String>;
    fn deliver_batch(&self, tab: &str, batch: Vec<SendBatchItem>) -> Result<(), String>;
    fn deliver_keys(&self, tab: &str, text: &str, strokes: &[KeyStroke]) -> Result<(), String>;
}

/// Build the ordered PTY actions from gateway strokes, mirroring the HTTP route:
/// a `\r` key becomes a Submit, every other key its raw bytes.
fn build_ordered(strokes: &[KeyStroke]) -> Result<Vec<OrderedPtyAction>, String> {
    let mut ordered = Vec::with_capacity(strokes.len());
    for stroke in strokes {
        match stroke {
            KeyStroke::Delay(ms) => ordered.push(OrderedPtyAction::Delay(
                std::time::Duration::from_millis(*ms),
            )),
            KeyStroke::Key(key) => {
                let bytes = crate::agent::keys::action_key_bytes(key)
                    .ok_or_else(|| format!("unknown action key: {key}"))?;
                if bytes == b"\r" {
                    ordered.push(OrderedPtyAction::Submit);
                } else {
                    ordered.push(OrderedPtyAction::Raw(bytes));
                }
            }
        }
    }
    Ok(ordered)
}

impl DeliverySeam for super::ServiceContext {
    fn deliver_enveloped(
        &self,
        to_tab: &str,
        envelope: MessageEnvelope,
        body: &str,
    ) -> Result<Delivery, String> {
        Messenger::deliver(self, to_tab, envelope, body)
    }

    fn deliver_text(&self, tab: &str, text: &str) -> Result<(), String> {
        self.send_text_detached(tab, text);
        Ok(())
    }

    fn deliver_batch(&self, tab: &str, batch: Vec<SendBatchItem>) -> Result<(), String> {
        self.send_text_batch(tab, batch)
    }

    fn deliver_keys(&self, tab: &str, text: &str, strokes: &[KeyStroke]) -> Result<(), String> {
        let ordered = build_ordered(strokes)?;
        execute_ordered_actions(
            text,
            &ordered,
            |body, enter| {
                if enter {
                    self.send_text(tab, body)
                } else {
                    self.insert_text(tab, body)
                }
            },
            |bytes| self.write_raw(tab, bytes),
            await_action_deadline,
        )
    }
}

impl super::ServiceContext {
    /// Deliver an enveloped machine/system message through the optimistic gateway.
    /// Delivery never starts a worker turn or touches its report obligation.
    /// Task dispatch arms that obligation explicitly.
    pub(crate) fn gateway_deliver(
        &self,
        target: &str,
        envelope: MessageEnvelope,
        body: &str,
        class: DeliveryClass,
    ) -> Result<Delivery, String> {
        let receipt = self
            .gateway
            .submit(
                self,
                OutboundMessage {
                    target: target.to_string(),
                    body: MessageBody::Text {
                        body: body.to_string(),
                    },
                    envelope: Some(envelope),
                    class,
                    origin: MessageOrigin::System,
                    idempotency_key: None,
                },
            )
            .map_err(|e| e.to_string())?;
        if class == DeliveryClass::AgentTraffic
            && self
                .plan_store
                .task_binding_for_tab(target)
                .and_then(|(_, task_id)| self.plan_store.show_task(&task_id))
                .is_some_and(|detail| detail.task.status == crate::plan::TaskStatus::InProgress)
        {
            self.gateway.require_worker_report(target);
        }
        Ok(receipt.delivery.unwrap_or(Delivery::Pty {
            text: body.to_string(),
        }))
    }
}

/// PHASE 1 wraps `Result<_, String>` paths, so failures are classified by the
/// structural markers those paths already emit until typed errors land upstream.
fn classify(target: &str, err: String) -> DeliveryError {
    let low = err.to_lowercase();
    if low.contains("not found")
        || low.contains("Tab missing")
        || low.contains("has no pty")
        || low.contains("did not start")
        || low.contains("closed before pty")
    {
        DeliveryError::TabNotFound {
            target: target.to_string(),
        }
    } else if low.contains("submit not confirmed")
        || low.contains("delivery_uncertain")
        || low.contains("not acknowledged")
    {
        DeliveryError::DeliveredUnverified { detail: err }
    } else {
        DeliveryError::Transport { detail: err }
    }
}

/// Bounded LRU keyed by origin+target+key. Recency bumps on hit and insert.
struct IdempotencyStore {
    cap: usize,
    map: HashMap<String, Result<DeliveryReceipt, DeliveryError>>,
    order: VecDeque<String>,
}

impl IdempotencyStore {
    fn new(cap: usize) -> Self {
        Self {
            cap: cap.max(1),
            map: HashMap::new(),
            order: VecDeque::new(),
        }
    }

    fn bump(&mut self, key: &str) {
        if let Some(pos) = self.order.iter().position(|k| k == key) {
            self.order.remove(pos);
        }
        self.order.push_back(key.to_string());
    }

    fn get(&mut self, key: &str) -> Option<Result<DeliveryReceipt, DeliveryError>> {
        let hit = self.map.get(key).cloned()?;
        self.bump(key);
        Some(hit)
    }

    fn put(&mut self, key: String, value: Result<DeliveryReceipt, DeliveryError>) {
        self.map.insert(key.clone(), value);
        self.bump(&key);
        while self.order.len() > self.cap {
            if let Some(evicted) = self.order.pop_front() {
                self.map.remove(&evicted);
            }
        }
    }
}

/// Gateway for bounded delivery coordination state.
pub struct MessageGateway {
    idempotency: Mutex<IdempotencyStore>,
    worker_report_required: Mutex<HashSet<String>>,
    #[cfg(test)]
    delivery_observer: Mutex<Option<std::sync::mpsc::Sender<String>>>,
}

impl Default for MessageGateway {
    fn default() -> Self {
        Self::with_capacity(IDEMPOTENCY_CAPACITY)
    }
}

impl MessageGateway {
    pub fn new() -> Self {
        Self::default()
    }

    pub fn with_capacity(cap: usize) -> Self {
        Self {
            idempotency: Mutex::new(IdempotencyStore::new(cap)),
            worker_report_required: Mutex::new(HashSet::new()),
            #[cfg(test)]
            delivery_observer: Mutex::new(None),
        }
    }

    pub(crate) fn require_worker_report(&self, tab_id: &str) {
        self.worker_report_required
            .lock()
            .insert(tab_id.to_string());
    }

    #[allow(dead_code)]
    pub(crate) fn clear_worker_report_requirement(&self, tab_id: &str) {
        self.worker_report_required.lock().remove(tab_id);
    }

    pub(crate) fn take_worker_report_requirement(&self, tab_id: &str) -> bool {
        self.worker_report_required.lock().remove(tab_id)
    }

    /// Non-destructive probe of the obligation state, for assertions.
    #[cfg(test)]
    pub(crate) fn worker_report_required(&self, tab_id: &str) -> bool {
        self.worker_report_required.lock().contains(tab_id)
    }

    #[cfg(test)]
    pub(crate) fn set_delivery_observer_for_test(&self, observer: std::sync::mpsc::Sender<String>) {
        *self.delivery_observer.lock() = Some(observer);
    }

    pub fn submit<S: DeliverySeam>(
        &self,
        seam: &S,
        msg: OutboundMessage,
    ) -> Result<DeliveryReceipt, DeliveryError> {
        let dedup_key = msg
            .idempotency_key
            .as_ref()
            .map(|k| format!("{:?}|{}|{}", msg.origin, msg.target, k));

        if let Some(ref key) = dedup_key {
            if let Some(cached) = self.idempotency.lock().get(key) {
                return replay(cached);
            }
        }

        let outcome = self.dispatch(seam, &msg);

        #[cfg(test)]
        if outcome.is_ok() {
            if let Some(observer) = self.delivery_observer.lock().clone() {
                let _ = observer.send(msg.target.clone());
            }
        }

        if let Some(key) = dedup_key {
            self.idempotency.lock().put(key, outcome.clone());
        }
        outcome
    }

    fn dispatch<S: DeliverySeam>(
        &self,
        seam: &S,
        msg: &OutboundMessage,
    ) -> Result<DeliveryReceipt, DeliveryError> {
        let key = msg.idempotency_key.clone();
        match &msg.body {
            MessageBody::Text { body } => match &msg.envelope {
                Some(envelope) => {
                    let delivery = seam
                        .deliver_enveloped(&msg.target, envelope.clone(), body)
                        .map_err(|e| classify(&msg.target, e))?;
                    Ok(receipt(Some(delivery), key))
                }
                None => {
                    seam.deliver_text(&msg.target, body)
                        .map_err(|e| classify(&msg.target, e))?;
                    Ok(receipt(None, key))
                }
            },
            MessageBody::Batch(items) => {
                seam.deliver_batch(&msg.target, items.clone())
                    .map_err(|e| classify(&msg.target, e))?;
                Ok(receipt(None, key))
            }
            MessageBody::Keys { text, strokes } => {
                seam.deliver_keys(&msg.target, text, strokes)
                    .map_err(|e| classify(&msg.target, e))?;
                Ok(receipt(None, key))
            }
        }
    }
}

fn receipt(delivery: Option<Delivery>, key: Option<String>) -> DeliveryReceipt {
    DeliveryReceipt {
        delivery,
        dedup_hit: false,
        idempotency_key: key,
    }
}

/// A cached success replays with `dedup_hit=true`; a cached error replays verbatim.
fn replay(
    cached: Result<DeliveryReceipt, DeliveryError>,
) -> Result<DeliveryReceipt, DeliveryError> {
    cached.map(|mut r| {
        r.dedup_hit = true;
        r
    })
}

