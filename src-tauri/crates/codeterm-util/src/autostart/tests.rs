use super::*;

const MACOS_AGENT: MacosLaunchAgent<'_> = MacosLaunchAgent {
    label: "com.domios.dev.fixture",
    bundle_id: MACOS_LABEL,
    environment: &[("CODETERM_DEV_API_PORT", "7748")],
};

#[test]
fn linux_unit_refresh_requires_the_exact_ownership_marker() {
    let desired = build_linux_unit("/usr/bin/domios", "/usr/bin/domios-app");
    assert!(refreshed_linux_unit(
        "[Service]\nRestart=always\n",
        "/usr/bin/domios",
        "/usr/bin/domios-app"
    )
    .is_none());
    assert!(refreshed_linux_unit(&desired, "/usr/bin/domios", "/usr/bin/domios-app").is_none());
    let stale = desired.replace("Restart=on-failure", "Restart=always");
    assert_eq!(
        refreshed_linux_unit(&stale, "/usr/bin/domios", "/usr/bin/domios-app"),
        Some(desired)
    );
    assert!(refreshed_linux_unit("# Generated by Domios impersonation\n", "cli", "app").is_none());
}

