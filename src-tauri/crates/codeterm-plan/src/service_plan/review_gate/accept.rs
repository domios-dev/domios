use super::*;

pub(super) fn follow_up(
    parent: &Task,
    fid: String,
    key: Option<String>,
    risk: &str,
    now_ms: u64,
) -> Task {
    Task {
        files: Default::default(),
        id: fid.clone(),
        name: format!("Follow-up hardening: {}", parent.name),
        kind: "implement".into(),
        model: None,
        speed: None,
        model_rationale: None,
        personality: None,
        personality_provenance: None,
        acceptance_criteria: vec![],
        external_refs: vec![],
        test_plan: None,
        qa_plan: None,
        correctness: None,
        status: TaskStatus::Pending,
        review_stage: ReviewStage::Review,
        qa_state: None,
        review_round: 0,
        review_oracle: None,
        review_evidence: vec![],
        key,
        review_override: None,
        review_audit: vec![],
        status_label: Some("residual risk from bounded review".into()),
        priority: parent.priority.clone(),
        created_at: now_ms,
        updated_at: now_ms,
        status_changed_at: now_ms,
        handle: None,
        tags: vec![],
        section_ids: parent.section_ids.clone(),
        body: format!("Residual risk documented at round bound: {risk}"),
        role_guidance: None,
        executor_role: parent.executor_role.clone(),
        competition: None,
        intent: None,
        execution_intent: parent.execution_intent,
        parent_task_id: Some(parent.id.clone()),
        depends_on: vec![],
        assigned_tab_id: None,
        lane: Default::default(),
        taken_by_role: None,
        peer: None,
        group: parent.group.clone(),
        canvas: Default::default(),
        milestones: vec![],
        execution_attempts: vec![],
        pause_reason: None,
        interruption: Default::default(),
        attachments: vec![],
    }
}
