CREATE TABLE mem_items (
    id TEXT PRIMARY KEY,
    uid TEXT NOT NULL UNIQUE,
    kind TEXT NOT NULL,
    scope TEXT NOT NULL,
    title TEXT NOT NULL,
    summary TEXT,
    area TEXT,
    tags_json TEXT NOT NULL DEFAULT '[]',
    body_inline TEXT,
    body_blob_path TEXT,
    source TEXT,
    importance DOUBLE PRECISION NOT NULL DEFAULT 3.0,
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL,
    accessed_at TEXT,
    access_count BIGINT NOT NULL DEFAULT 0,
    recurrence_count BIGINT NOT NULL DEFAULT 0,
    source_path TEXT,
    source_size BIGINT,
    source_mtime TEXT,
    evidence_count BIGINT NOT NULL DEFAULT 1,
    false_fire_count BIGINT NOT NULL DEFAULT 0,
    promotion_threshold BIGINT,
    is_pinned_wakeup BIGINT NOT NULL DEFAULT 0,
    seed_fingerprint TEXT
);
CREATE INDEX mem_kind ON mem_items(kind);
CREATE INDEX mem_scope ON mem_items(scope);
CREATE INDEX mem_area ON mem_items(area);
CREATE INDEX mem_importance ON mem_items(importance DESC);
CREATE INDEX mem_created ON mem_items(created_at DESC);
CREATE INDEX mem_pinned ON mem_items(is_pinned_wakeup) WHERE is_pinned_wakeup=1;

CREATE TABLE mem_fts (
    rowid BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mem_id TEXT NOT NULL,
    title TEXT,
    summary TEXT,
    body TEXT,
    tags TEXT,
    document TSVECTOR GENERATED ALWAYS AS (
        setweight(to_tsvector('simple', coalesce(title,'')), 'A') ||
        setweight(to_tsvector('simple', coalesce(summary,'')), 'B') ||
        setweight(to_tsvector('simple', coalesce(body,'')), 'C') ||
        setweight(to_tsvector('simple', coalesce(tags,'')), 'B')
    ) STORED
);
CREATE INDEX mem_fts_document ON mem_fts USING GIN(document);
CREATE INDEX mem_fts_id ON mem_fts(mem_id);

CREATE TABLE entities (
    id TEXT PRIMARY KEY,
    entity_type TEXT NOT NULL,
    scope TEXT NOT NULL,
    properties_json TEXT NOT NULL DEFAULT '{}',
    created_at TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
CREATE INDEX entities_type ON entities(entity_type);
CREATE TABLE relations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_id TEXT NOT NULL,
    relation_type TEXT NOT NULL,
    to_id TEXT NOT NULL,
    scope TEXT NOT NULL,
    valid_from TEXT NOT NULL,
    valid_to TEXT,
    confidence DOUBLE PRECISION NOT NULL DEFAULT 1.0,
    properties_json TEXT NOT NULL DEFAULT '{}',
    created_at TEXT NOT NULL,
    reason TEXT,
    UNIQUE(from_id,relation_type,to_id,valid_from)
);
CREATE INDEX relations_from ON relations(from_id);
CREATE INDEX relations_to ON relations(to_id);
CREATE INDEX relations_type ON relations(relation_type);
CREATE INDEX relations_valid ON relations(valid_from,valid_to);
CREATE UNIQUE INDEX relations_active ON relations(from_id,relation_type,to_id,scope) WHERE valid_to IS NULL;
CREATE TABLE entity_aliases (
    alias_id TEXT PRIMARY KEY,
    canonical_id TEXT NOT NULL,
    created_at TEXT NOT NULL
);
CREATE INDEX aliases_canonical ON entity_aliases(canonical_id);
CREATE TABLE mem_item_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    item_id TEXT NOT NULL,
    changed_at TEXT NOT NULL,
    changed_by TEXT NOT NULL,
    change_type TEXT NOT NULL,
    old_title TEXT,
    new_title TEXT,
    old_body TEXT,
    new_body TEXT,
    old_importance DOUBLE PRECISION,
    new_importance DOUBLE PRECISION,
    old_kind TEXT,
    new_kind TEXT,
    reason TEXT
);
CREATE INDEX history_item ON mem_item_history(item_id,changed_at DESC);
CREATE INDEX history_actor ON mem_item_history(changed_by);
CREATE TABLE graph_pinned_positions (
    mem_id TEXT PRIMARY KEY REFERENCES mem_items(id) ON DELETE CASCADE,
    x DOUBLE PRECISION NOT NULL,
    y DOUBLE PRECISION NOT NULL,
    updated_at BIGINT NOT NULL
);
CREATE TABLE mem_embedder (
    singleton BIGINT PRIMARY KEY CHECK(singleton=1),
    provider TEXT NOT NULL,
    model TEXT NOT NULL,
    dimension BIGINT NOT NULL CHECK(dimension BETWEEN 1 AND 16000),
    stamped_at TEXT NOT NULL
);
CREATE TABLE mem_vector_pending (mem_id TEXT PRIMARY KEY, reason TEXT NOT NULL, queued_at TEXT NOT NULL);
CREATE TABLE solution_metadata (item_id TEXT PRIMARY KEY REFERENCES mem_items(id) ON DELETE CASCADE, metadata_json TEXT NOT NULL);
CREATE TABLE blueprint_call_scopes (item_id TEXT PRIMARY KEY, area TEXT NOT NULL, team TEXT NOT NULL);
CREATE TABLE blueprint_call_revisions (
    item_id TEXT NOT NULL, hash TEXT NOT NULL, area TEXT NOT NULL, team TEXT NOT NULL, document TEXT NOT NULL,
    PRIMARY KEY(item_id,hash,area,team)
);
CREATE TABLE blueprint_index (
    item_id TEXT PRIMARY KEY REFERENCES mem_items(id) ON DELETE CASCADE,
    document_hash TEXT NOT NULL, canon TEXT NOT NULL, gists TEXT NOT NULL,
    signature_json TEXT NOT NULL, enrichment_json TEXT
);
CREATE TABLE blueprint_vectors (
    item_id TEXT NOT NULL REFERENCES mem_items(id) ON DELETE CASCADE,
    slot TEXT NOT NULL, ordinal BIGINT NOT NULL, text TEXT NOT NULL,
    embedding BYTEA NOT NULL, provider TEXT NOT NULL, model TEXT NOT NULL, dimension BIGINT NOT NULL,
    PRIMARY KEY(item_id,slot,ordinal)
);
CREATE TABLE blueprint_v1_cleanup_receipt (id BIGINT PRIMARY KEY CHECK(id=1), removed_count BIGINT NOT NULL, completed_at TEXT NOT NULL);
CREATE TABLE mem_source_tombstones (source_key TEXT PRIMARY KEY, deleted_at TEXT NOT NULL);
CREATE TABLE mem_precompact_purges (item_id TEXT PRIMARY KEY, history_rows BIGINT NOT NULL, history_body_bytes BIGINT NOT NULL, purged_at TEXT NOT NULL);
CREATE TABLE mem_precompact_purge_blobs (item_id TEXT NOT NULL, path TEXT NOT NULL, body_bytes BIGINT NOT NULL, PRIMARY KEY(item_id,path));
CREATE TABLE lesson_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_uid TEXT NOT NULL, machine_id TEXT NOT NULL, action TEXT NOT NULL CHECK(action IN ('promoted','demoted')),
    ts TEXT NOT NULL, reason TEXT
