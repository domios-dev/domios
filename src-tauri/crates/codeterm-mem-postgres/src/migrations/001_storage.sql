    actor TEXT NOT NULL, details_json TEXT NOT NULL DEFAULT '{}'
);
CREATE TABLE mem_blobs (name TEXT PRIMARY KEY, body BYTEA NOT NULL);
CREATE TABLE mem_shadow (
    target TEXT NOT NULL, unit_key TEXT NOT NULL, text_hash BYTEA NOT NULL, vectors BYTEA,
    PRIMARY KEY(target,unit_key)
);
