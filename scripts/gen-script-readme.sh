#!/usr/bin/env bash
# Caller: scripts check-script-catalog.sh; run directly to regenerate scripts/README.md
# Generate scripts/README.md from each script's "Caller:" header and scripts/catalog-extra.txt.
# Usage: bash scripts/gen-script-readme.sh [--check]
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"

script_catalog_entries() {
  git ls-files scripts | awk -F/ '{print $2}' | sort -u |
    grep -vxE 'README\.md|catalog-extra\.txt|catalog-removed\.md'
}

script_caller() {
  local entry="$1" line
  line="$(head -n 8 "scripts/$entry" 2>/dev/null | tr -d '\r' | grep -m1 -E '^(#|//) Caller: ' || true)"
  if [ -n "$line" ]; then
    printf '%s\n' "${line#*Caller: }"
    return
  fi
  grep -m1 -F "$entry | " scripts/catalog-extra.txt 2>/dev/null | tr -d '\r' | sed 's/^[^|]*| //' || true
}

render() {
  printf '# scripts/\n\nGenerated by `bash scripts/gen-script-readme.sh` from each file'"'"'s `Caller:` header and `catalog-extra.txt`; do not edit by hand.\n'
  printf 'The gate `scripts/check-script-catalog.sh` fails on a script with no header or entry, on one nothing calls, and on a stale README. Removed scripts and their grep evidence: `catalog-removed.md`.\n\n'
  printf '| Entry | Caller |\n|---|---|\n'
  script_catalog_entries | while IFS= read -r entry; do
    printf '| `%s` | %s |\n' "$entry" "$(script_caller "$entry" | sed 's/|/\|/g')"
  done
}

if [ "${BASH_SOURCE[0]}" = "$0" ]; then
  if [ "${1:-}" = "--check" ]; then
    render | diff -q --strip-trailing-cr - scripts/README.md >/dev/null || { echo "ERROR: scripts/README.md is stale; run bash scripts/gen-script-readme.sh" >&2; exit 1; }
  else
    render > scripts/README.md
  fi
fi
