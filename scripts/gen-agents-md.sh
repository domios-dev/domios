#!/usr/bin/env bash
# Generate AGENTS.md from CLAUDE.md.
#
# CLAUDE.md is canonical (battle-tested, full of Claude Code delegation
# mechanics). AGENTS.md is the vendor-neutral mirror that OpenAI Codex — and
# any other agent following the agents.md convention — reads natively, so
# non-Claude workers land with the same hard rules (prod 7685, no auto-commit,
# lock ordering, file-size discipline) instead of a blank slate.
#
# The mirror is a deterministic transform of CLAUDE.md: a fixed header plus a
# small, documented set of translations of Claude-Code-harness-specific syntax
# into the equivalent `codeterm` CLI form. Because it is deterministic,
# check-agents-md.sh can re-run this and diff to detect staleness.
#
# Usage:
#   scripts/gen-agents-md.sh            # write AGENTS.md at repo root
#   scripts/gen-agents-md.sh --stdout   # print to stdout (used by the staleness check)

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/CLAUDE.md"
OUT="$ROOT/AGENTS.md"

if [ ! -f "$SRC" ]; then
    echo "ERROR: $SRC not found" >&2
    exit 1
fi

render() {
    cat <<'HEADER'
<!-- GENERATED FILE — DO NOT EDIT BY HAND.
     Source of truth: CLAUDE.md. Regenerate with: scripts/gen-agents-md.sh
     CI (scripts/check-agents-md.sh) fails if this file drifts from CLAUDE.md.

     Why this file exists: CLAUDE.md is Claude Code's native instruction file.
     AGENTS.md is the cross-vendor convention OpenAI Codex (and others) read.
     This repo's team is Claude Code + Codex, so both files must carry the same
     rules without maintaining two divergent rulebooks — hence this generated
     mirror. Where the text below says "Claude", every agent on the team
     (Codex/GPT included) applies the identical rule.

     NOTE on the user-global rule "never edit AGENTS.md — auto-generated by
     CodeTerm": that rule targets the General Agent's *home-directory*
     instruction files that CodeTerm regenerates at runtime. It does NOT apply
     to this checked-in repo artifact, which is generated from CLAUDE.md by the
     script above and is version-controlled like any other source doc. -->

HEADER

    # Translate Claude-Code Task-tool invocation syntax to the vendor-neutral
    # CLI spawn form. The prompt strings in CLAUDE.md contain no nested double
    # quotes, so [^"]* is a safe, deterministic match.
    #   Agent(subagent_type="general-purpose", prompt="X")  ->  codeterm agent spawn claude --task "X"
    #   Agent(subagent_type="role")                          ->  codeterm agent spawn claude (role: role)
    perl -pe '
        s/Agent\(subagent_type="general-purpose",\s*prompt=("[^"]*")\)/codeterm agent spawn claude --task $1/g;
        s/Agent\(subagent_type="([^"]*)"\)/codeterm agent spawn claude (role: $1)/g;
    ' "$SRC"
}

if [ "${1:-}" = "--stdout" ]; then
    render
else
    render >"$OUT"
    echo "Generated $OUT from CLAUDE.md"
fi
