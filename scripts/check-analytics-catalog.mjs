// Caller: scripts check-analytics-catalog.test.mjs
import { readFileSync, writeFileSync, existsSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { spawnSync } from "node:child_process";

const rootFlag = process.argv.indexOf("--root");
const root = rootFlag >= 0 ? resolve(process.argv[rootFlag + 1]) : fileURLToPath(new URL("../", import.meta.url));
const read = (path) => readFileSync(resolve(root, path), "utf8");
const schema = JSON.parse(read("src-tauri/crates/codeterm-analytics/catalog.schema.json"));
const providers = readdirSync(resolve(root, "plugins")).filter((id) => id.startsWith("provider-") && existsSync(resolve(root, `plugins/${id}/plugin.json`))).map((id) => JSON.parse(read(`plugins/${id}/plugin.json`))).sort((a,b) => a.id.localeCompare(b.id));
schema.enums.ProviderId = [...providers.map((p) => p.id), "other"];
const variant = (value) => value.split(/[^a-zA-Z0-9]+/).filter(Boolean).map((s) => s[0].toUpperCase() + s.slice(1)).join("");
const quoted = (v) => JSON.stringify(v);
let rust = 'use serde::{Deserialize, Serialize};\nuse super::Version;\n';
for (const [name, values] of Object.entries(schema.enums)) {
  rust += `#[derive(Clone, Copy, Debug, Serialize, Deserialize, PartialEq, Eq, PartialOrd, Ord)]\npub enum ${name} {\n`;
  rust += values.map((v) => `#[serde(rename = ${quoted(v)})]\n${variant(v)},\n`).join("");
  rust += `}\nimpl ${name} { pub fn from_catalog(value: &str) -> Option<Self> { match value {\n`;
  rust += values.map((v) => `${quoted(v)} => Some(Self::${variant(v)}),\n`).join("");
  rust += '_ => None, } } }\n';
}
rust += '#[derive(Clone, Debug, Serialize, Deserialize, PartialEq, Eq)]\n#[serde(tag = "event_type", content = "event_properties", rename_all = "snake_case", deny_unknown_fields)]\npub enum Event {\n';
for (const [name, fields] of Object.entries(schema.events)) rust += `${variant(name)} { ${Object.entries(fields).map(([field,type])=>`${field}: ${type},`).join(" ")} },\n`;
rust += '}\n';
const formatted = spawnSync("rustfmt", ["--edition", "2021", "--emit", "stdout"], {input:rust,encoding:"utf8"});
if (formatted.status !== 0) throw new Error(formatted.stderr);
let ts = '// Generated by scripts/check-analytics-catalog.mjs --write.\n';
for (const [name, values] of Object.entries(schema.enums)) ts += `export type ${name} = ${values.map(quoted).join(" | ")};\n`;
ts += 'export type Version = `${number}.${number}.${number}`;\nexport type ProductEvent =\n';
for (const [name, fields] of Object.entries(schema.events)) ts += `  | { event_type: ${quoted(name)}; event_properties: ${Object.keys(fields).length ? `{ ${Object.entries(fields).map(([f,t])=>`${f}: ${t === "u32" ? "number" : t.startsWith("Option<") ? t.slice(7,-1) + " | null" : t}`).join("; ")} }` : "Record<string, never>"} }\n`;
ts += ';\n';
ts += `export const PRODUCT_EVENT_CATALOG = ${JSON.stringify(schema.events, null, 2)} as const;\n`;
ts += `export const PRODUCT_EVENT_ENUMS = ${JSON.stringify(schema.enums, null, 2)} as const;\n`;
const table = ["| Event | Properties |", "|---|---|", ...Object.entries(schema.events).map(([name, fields]) => `| \`${name}\` | ${Object.entries(fields).map(([field, type]) => `\`${field}\`: ${type.replace("<", "&lt;").replace(">", "&gt;")}`).join(", ") || "None"} |`), "", ...Object.entries(schema.enums).map(([name, values]) => `- **${name}:** ${values.map((value) => `\`${value}\``).join(", ")}`)].join("\n");
const docPath = "prod-docs/ACCOUNT.md";
const doc = read(docPath);
const documented = doc.replace(/<!-- analytics-catalog:start -->[\s\S]*?<!-- analytics-catalog:end -->/, `<!-- analytics-catalog:start -->\n${table}\n<!-- analytics-catalog:end -->`);
let stale = false;
for (const [path, content] of [["src-tauri/crates/codeterm-analytics/src/catalog/generated.rs", formatted.stdout], ["src/lib/productAnalytics.generated.ts",ts], [docPath, documented]]) {
  if (process.argv.includes("--write")) writeFileSync(resolve(root,path),content);
  else if (!existsSync(resolve(root,path)) || read(path) !== content) { console.error(`Stale analytics catalog: ${path}. Run node scripts/check-analytics-catalog.mjs --write`); stale = true; }
}
if (stale) process.exit(1);
console.log("Analytics catalog is current");
