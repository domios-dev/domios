import { cp, mkdir, readFile, readdir, unlink } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "gen");
const packageOutputs = ["packages/chat-core/src/gen", "packages/plugin-sdk/src/gen"];
const generatedHeader = "// This file was generated by [ts-rs]";

async function clearGenerated(directory) {
  await mkdir(directory, { recursive: true });
  for (const name of await readdir(directory)) {
    if (!name.endsWith(".ts")) continue;
    const file = path.join(directory, name);
    const contents = await readFile(file, "utf8");
    if (!contents.startsWith(generatedHeader)) {
      throw new Error(`Refusing to replace non-generated file: ${file}`);
    }
    await unlink(file);
  }
}

await clearGenerated(output);
for (const packagePath of packageOutputs) {
  await clearGenerated(path.join(root, packagePath));
}

const env = {
  ...process.env,
  TS_RS_EXPORT_DIR: output,
  TS_RS_LARGE_INT: "number",
};
const result = spawnSync(
  "cargo",
  ["run", "--manifest-path", "src-tauri/Cargo.toml", "-p", "codeterm-types", "--bin", "export-chat-types"],
  { cwd: root, env, stdio: "inherit" },
);

if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);

const generated = (await readdir(output)).filter((name) => name.endsWith(".ts"));
if (generated.length === 0) throw new Error("ts-rs did not emit any TypeScript files");

for (const packagePath of packageOutputs) {
  const destination = path.join(root, packagePath);
  await mkdir(destination, { recursive: true });
  for (const name of generated) {
    await cp(path.join(output, name), path.join(destination, name));
  }
}
