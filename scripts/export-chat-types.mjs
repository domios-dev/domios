// Caller: package.json script
import { mkdir, mkdtemp, readFile, readdir, rm, unlink, writeFile } from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";
import { exportAttachmentLimits } from "./export-attachment-limits.mjs";

await exportAttachmentLimits();
if (process.argv.includes("--constants-only")) process.exit(0);

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "gen");
const chatOutput = "packages/chat-core/src/gen";
const sdkOutput = "packages/plugin-sdk/src/gen";
const generatedHeader = "// This file was generated by [ts-rs]";

// ts-rs writes dependency types such as serde_json's JsonValue into subdirectories.
async function generatedFiles(directory, relative = "") {
  const entries = await readdir(path.join(directory, relative), { withFileTypes: true }).catch(
    (error) => (error.code === "ENOENT" ? [] : Promise.reject(error)),
  );
  const files = [];
  for (const entry of entries) {
    const child = path.join(relative, entry.name);
    if (entry.isDirectory()) files.push(...(await generatedFiles(directory, child)));
    else if (entry.isFile() && entry.name.endsWith(".ts")) files.push(child);
  }
  return files;
}

async function synchronize(directory, sources) {
  const contents = new Map();
  for (const source of sources) {
    const files = await generatedFiles(source);
    if (files.length === 0) throw new Error(`No generated TypeScript files under ${source}`);
    for (const relative of files) {
      const body = await readFile(path.join(source, relative), "utf8");
      if (contents.has(relative) && contents.get(relative) !== body) {
        throw new Error(`Conflicting Rust exports: ${relative}`);
      }
      contents.set(relative, body);
    }
  }
  await mkdir(directory, { recursive: true });
  for (const relative of await generatedFiles(directory)) {
    const file = path.join(directory, relative);
    const body = await readFile(file, "utf8");
    if (!body.startsWith(generatedHeader)) {
      throw new Error(`Refusing to replace non-generated file: ${file}`);
    }
    if (!contents.has(relative)) await unlink(file);
  }
  for (const [relative, body] of contents) {
    const file = path.join(directory, relative);
    const previous = await readFile(file, "utf8").catch((error) =>
      error.code === "ENOENT" ? null : Promise.reject(error),
    );
    if (previous === body) continue;
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, body);
  }
  console.log(`exported ${contents.size} file(s) into ${path.relative(root, directory)}`);
}

const staging = await mkdtemp(path.join(os.tmpdir(), "domios-protocol-types-"));
try {
  const chat = path.join(staging, "chat");
  const protocol = path.join(staging, "protocol");
  const sdk = path.join(staging, "sdk");
  const result = spawnSync("cargo", ["run", "--manifest-path", "src-tauri/Cargo.toml", "-p", "codeterm-protocol-export"], {
    cwd: root,
    env: { ...process.env, TS_RS_EXPORT_DIR: chat, DOMIOS_PROTOCOL_EXPORT_DIR: protocol, DOMIOS_SDK_EXPORT_DIR: sdk, TS_RS_LARGE_INT: "number" },
    stdio: "inherit",
  });
  if (result.error) throw result.error;
  if (result.status !== 0) process.exitCode = result.status ?? 1;
  else {
    await synchronize(output, [chat, protocol]);
    await synchronize(path.join(root, chatOutput), [chat]);
    await synchronize(path.join(root, sdkOutput), [chat, sdk]);
  }
} finally {
  await rm(staging, { recursive: true, force: true });
}
