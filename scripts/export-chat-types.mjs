import { cp, mkdir, readFile, readdir, unlink } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { spawnSync } from "node:child_process";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const output = path.join(root, "gen");
const packageOutputs = ["packages/chat-core/src/gen", "packages/plugin-sdk/src/gen"];
const generatedHeader = "// This file was generated by [ts-rs]";

// ts-rs writes dependency types such as serde_json's JsonValue into subdirectories.
async function generatedFiles(directory, relative = "") {
  const entries = await readdir(path.join(directory, relative), { withFileTypes: true }).catch(
    (error) => (error.code === "ENOENT" ? [] : Promise.reject(error)),
  );
  const files = [];
  for (const entry of entries) {
    const child = path.join(relative, entry.name);
    if (entry.isDirectory()) files.push(...(await generatedFiles(directory, child)));
    else if (entry.isFile() && entry.name.endsWith(".ts")) files.push(child);
  }
  return files;
}

async function clearGenerated(directory) {
  await mkdir(directory, { recursive: true });
  for (const relative of await generatedFiles(directory)) {
    const file = path.join(directory, relative);
    const contents = await readFile(file, "utf8");
    if (!contents.startsWith(generatedHeader)) {
      throw new Error(`Refusing to replace non-generated file: ${file}`);
    }
    await unlink(file);
  }
}

await clearGenerated(output);
for (const packagePath of packageOutputs) {
  await clearGenerated(path.join(root, packagePath));
}

const env = {
  ...process.env,
  TS_RS_EXPORT_DIR: output,
  TS_RS_LARGE_INT: "number",
};
const result = spawnSync(
  "cargo",
  ["run", "--manifest-path", "src-tauri/Cargo.toml", "-p", "codeterm-types", "--bin", "export_chat_types"],
  { cwd: root, env, stdio: "inherit" },
);

if (result.error) throw result.error;
if (result.status !== 0) process.exit(result.status ?? 1);

const generated = await generatedFiles(output);
if (generated.length === 0) throw new Error("ts-rs did not emit any TypeScript files");

for (const packagePath of packageOutputs) {
  const destination = path.join(root, packagePath);
  for (const relative of generated) {
    await mkdir(path.dirname(path.join(destination, relative)), { recursive: true });
    await cp(path.join(output, relative), path.join(destination, relative));
  }
}

console.log(`exported ${generated.length} file(s) into gen/ and ${packageOutputs.join(", ")}:`);
for (const relative of generated) console.log(`  ${relative.split(path.sep).join("/")}`);
