import { readFile, mkdir, writeFile } from "node:fs/promises";

export async function exportAttachmentLimits() {
  const source = await readFile(new URL("../src-tauri/crates/codeterm-api/src/web_routes.rs", import.meta.url), "utf8");
  const expression = source.match(/pub const MAX_TEMP_FILE_DECODED_BYTES: usize = ([\d *]+);/)?.[1];
  if (!expression) throw new Error("Cannot export MAX_TEMP_FILE_DECODED_BYTES");
  const bytes = expression.split("*").reduce((value, factor) => value * Number(factor.trim()), 1);
  if (!Number.isSafeInteger(bytes) || bytes <= 0) throw new Error("Invalid attachment limit");
  await mkdir(new URL("../generated/config/", import.meta.url), { recursive: true });
  await writeFile(new URL("../generated/config/attachmentLimits.ts", import.meta.url),
    `// Generated by scripts/export-attachment-limits.mjs from codeterm-api web_routes.rs.\nexport const MAX_TEMP_FILE_DECODED_BYTES = ${bytes};\n`);
}
