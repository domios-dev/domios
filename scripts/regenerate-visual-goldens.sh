#!/usr/bin/env bash
# Caller: package.json script; scripts check-visual-golden-edits.sh
set -euo pipefail

ROOT="$(git rev-parse --show-toplevel)"
cd "$ROOT"

SPEC="tests/playwright/suites/13-canvas/visual-regression.spec.ts"
REVIEW="tests/playwright/visual-goldens-reviewed-diff.md"

if ! curl -fsS http://127.0.0.1:7686/api/health >/dev/null; then
  echo "dev daemon on 7686 is required before regenerating visual goldens" >&2
  exit 1
fi

rm -f "$REVIEW"

pnpm exec playwright test "$SPEC" \
  --config=tests/playwright/playwright.config.ts \
  --project=golden \
  --update-snapshots \
  --timeout=30000 \
  --global-timeout=600000 \
  --reporter=line

{
  echo "# Visual Golden Review"
  echo
  echo "Generated by \`scripts/regenerate-visual-goldens.sh\`."
  echo
  echo "Review checklist:"
  echo "- Inspect every changed PNG in the diff before committing."
  echo "- Commit this file with the baseline changes."
  echo
  echo "## Changed Files"
  echo
  git status --short -- "$SPEC" "tests/playwright/suites/13-canvas/visual-regression.spec.ts-snapshots" "$REVIEW" || true
  echo
  echo "## Diff Stat"
  echo
  git diff --stat -- "$SPEC" "tests/playwright/suites/13-canvas/visual-regression.spec.ts-snapshots" || true
} > "$REVIEW"

echo "Wrote $REVIEW"
echo "Review changed PNGs before committing."
