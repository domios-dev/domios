#!/usr/bin/env node
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { basename, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { parsedHeader, scopedSpecs, surfaceFromSpec, toPosix } from "../tests/playwright/helpers/spec-headers.mjs";

const root = resolve(fileURLToPath(new URL("..", import.meta.url)));
const suitesDir = resolve(root, "tests/playwright/suites");
const outputPath = resolve(root, "tests/playwright/COVERAGE_MAP.md");

function knownSurfaces(files, repoRoot) {
  return [...new Set(files.map((file) => surfaceFromSpec(file, repoRoot)))].sort();
}

function specTitle(file, header) {
  return header?.fields.get("WHAT:") ?? basename(file);
}

export function renderCoverageMap(files, surfaces = knownSurfaces(files, root), repoRoot = root) {
  const bySurface = new Map(surfaces.map((surface) => [surface, []]));
  for (const file of files) {
    const surface = surfaceFromSpec(file, repoRoot);
    const header = parsedHeader(file);
    const rel = toPosix(relative(repoRoot, file));
    if (!bySurface.has(surface)) {
      bySurface.set(surface, []);
    }
    bySurface.get(surface).push({ rel, title: specTitle(file, header) });
  }

  const sorted = [...bySurface.entries()].sort(([a], [b]) => a.localeCompare(b));
  const zero = sorted.filter(([, specs]) => specs.length === 0).map(([surface]) => surface);
  const lines = [
    "# Playwright Coverage Map",
    "",
    "> Generated by `node scripts/playwright-coverage-map.mjs`. Do not edit by hand.",
    "",
    "## Zero-Coverage Surfaces",
    "",
    zero.length === 0 ? "**NONE**" : zero.map((surface) => `- **${surface}**`).join("\n"),
    "",
    "## Surface Map",
    "",
  ];

  for (const [surface, specs] of sorted) {
    lines.push(`### ${surface}`, "");
    if (specs.length === 0) {
      lines.push("- **ZERO COVERAGE**", "");
      continue;
    }
    for (const spec of specs.sort((a, b) => a.rel.localeCompare(b.rel))) {
      lines.push(`- [${spec.rel}](../../${spec.rel}) - ${spec.title}`);
    }
    lines.push("");
  }

  return `${lines.join("\n").trimEnd()}\n`;
}

function main() {
  const check = process.argv.includes("--check");
  const files = scopedSpecs({ envName: "PW_COVERAGE_SCOPE", fallbackDir: suitesDir });
  const markdown = renderCoverageMap(files);
  if (check) {
    const current = existsSync(outputPath) ? readFileSync(outputPath, "utf8") : "";
    if (current !== markdown) {
      console.error("tests/playwright/COVERAGE_MAP.md is stale. Run node scripts/playwright-coverage-map.mjs.");
      process.exit(1);
    }
    console.log("Playwright coverage map OK");
    return;
  }

  writeFileSync(outputPath, markdown);
  console.log(`Wrote ${toPosix(relative(root, outputPath))}`);
}

// `file://${argv[1]}` only ever matched by coincidence on POSIX; a Windows argv[1]
// carries a drive letter and backslashes, so this guarded main() out of existence.
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  main();
}
