import assert from "node:assert/strict";
import {accountUsageSnapshot,ownRuntimeUsage,latestUsageSnapshot,runtimeLimitsSnapshot,runtimeTokenLabel,runtimeTokenBreakdown,runtimeAccountCreditsLabel,formatAccountCredits} from "./runtimeUsage";
import type {UsageSnapshot,RuntimeUsageProjection} from "../../types/usage";
const reading:RuntimeUsageProjection={tab_id:"own",thread_id:"thread",billing_mode:"subscription",token_usage:null,rate_limits:{captured_at:100,value:[{window:"primary",usedPercent:2,resetsAt:1000},{window:"secondary",usedPercent:0,resetsAt:2000}]}};
const snapshot={provider:"fixture",captured_at:100,runtime_usage:[reading]} as UsageSnapshot;
assert.equal(ownRuntimeUsage(snapshot,"foreign","thread"),null);
assert.equal(ownRuntimeUsage(snapshot,"own","old"),null);
assert.equal(ownRuntimeUsage(snapshot,"own","thread"),reading);
assert.equal(runtimeAccountCreditsLabel({kind:"balance",balance:"123.4500"}),"123.45");
assert.equal(runtimeAccountCreditsLabel({kind:"balance",balance:"0.00"}),null);
assert.equal(runtimeAccountCreditsLabel({kind:"unlimited"}),"Unlimited");
assert.equal(runtimeAccountCreditsLabel(undefined),null);
const resets={availableCount:3,nextExpiry:null,credits:null};
assert.deepEqual(runtimeLimitsSnapshot(snapshot,{...reading,resets}).resets,resets);
const limits=runtimeLimitsSnapshot(snapshot,reading);
assert.equal(limits.session_pct,2);
assert.equal(limits.weekly_pct,0);
assert.equal(limits.session_resets_at,1000);
const api={...reading,billing_mode:"api" as const,token_usage:{captured_at:200,value:{input_tokens:100,output_tokens:20,cache_read_tokens:30}}};
assert.equal(runtimeLimitsSnapshot(limits,api).session_pct,null);
const latest = {...snapshot, parsed_ok:true, captured_at:200, weekly_pct:11};
assert.equal(latestUsageSnapshot(latest,"own","thread")?.weekly_pct,11);
assert.equal(latestUsageSnapshot({...latest,captured_at:50},"own","thread")?.weekly_pct,0);
assert.equal(latestUsageSnapshot({...latest,captured_at:100},"own","thread")?.weekly_pct,11);
assert.equal(latestUsageSnapshot({...latest,runtime_usage:[{...reading,rate_limits:null,token_usage:{captured_at:300,value:{input_tokens:1,output_tokens:2}}}]},"own","thread")?.weekly_pct,11);
assert.equal(latestUsageSnapshot({...latest,runtime_usage:[api]},"own","thread")?.session_pct,null);
assert.equal(latestUsageSnapshot(latest,"foreign","thread"),null);
assert.equal(latestUsageSnapshot({...latest,runtime_usage:undefined})?.weekly_pct,11);
assert.equal(runtimeTokenLabel(api),"120 tokens");
assert.equal(runtimeTokenBreakdown(api),"Session input: 100; cached input: 30; cache write: 0; output: 20");
assert.equal(runtimeTokenLabel({...api,token_usage:{captured_at:200,value:{...api.token_usage.value,cost_micros:20000}}}),"120 tokens · $0.02");
assert.equal(runtimeTokenLabel({...api, token_usage:null}), "—");
console.log("PASS runtime usage: exact binding, windows, API tokens and optional cost");

assert.equal(formatAccountCredits("53200.2300300000"), "53,200.23");
assert.equal(formatAccountCredits("999.999"), "1,000");
assert.equal(formatAccountCredits("9007199254740993.125"), "9,007,199,254,740,993.13");
assert.equal(formatAccountCredits("0.0000000001"), "0");
assert.equal(formatAccountCredits("invalid"), "—");

const accountRow={provider:"fixture",captured_at:50,parsed_ok:true,session_pct:9,weekly_pct:4} as UsageSnapshot;
assert.equal(accountUsageSnapshot(accountRow),accountRow,"an account with no runtime readings shows its own row");
const older={...reading,tab_id:"older",rate_limits:{captured_at:90,value:[{window:"primary",usedPercent:1}]}};
const borrowed=accountUsageSnapshot({...accountRow,runtime_usage:[older,reading]});
assert.equal(borrowed?.session_pct,2,"the freshest subscription reading of the account wins, as on its own tabs");
const apiOnly={...reading,billing_mode:"api" as const};
assert.equal(accountUsageSnapshot({...accountRow,runtime_usage:[apiOnly]})?.session_pct,9,"another tab's API-billed tokens never stand in for account limits");
assert.equal(accountUsageSnapshot({...accountRow,parsed_ok:false,runtime_usage:[apiOnly]}),null);
