import assert from "node:assert/strict";
import { NAVIGATION_LIMIT, navigationRecord, optionalNavigationId, parentWhenMissing, readNavigation, writeNavigation } from "./viewerNavigation";

const values = new Map<string, string>();
const storage = { getItem: (key: string) => values.get(key) ?? null, setItem: (key: string, value: string) => { values.set(key, value); } };
writeNavigation(storage, "window-a", "workspace", "ws-a", optionalNavigationId);
assert.equal(readNavigation(storage, "window-a", "workspace", optionalNavigationId), "ws-a");
assert.equal(readNavigation(storage, "window-b", "workspace", optionalNavigationId), undefined);
assert.equal(readNavigation(storage, "window-a", "workspace", () => undefined), undefined);
assert.deepEqual(navigationRecord("broken"), {});
assert.deepEqual(navigationRecord("[]"), {});
assert.deepEqual(navigationRecord(" ".repeat(NAVIGATION_LIMIT + 1)), {});
for (let index = 0; index < 50; index++) writeNavigation(storage, "window-a", String(index), `id-${index}`, optionalNavigationId);
assert.equal(Object.keys(navigationRecord(values.get("window-a")!)).length, 24);
assert.equal(readNavigation(storage, "window-a", "0", optionalNavigationId), undefined);
writeNavigation(storage, "window-a", "49", "x".repeat(513), optionalNavigationId);
assert.equal(readNavigation(storage, "window-a", "49", optionalNavigationId), undefined);
const text = (value: unknown) => typeof value === "string" ? value : undefined;
writeNavigation(storage, "budget", "old", "a".repeat(10_000), text);
writeNavigation(storage, "budget", "new", "b".repeat(10_000), text);
assert.equal(readNavigation(storage, "budget", "old", text), undefined);
assert.equal(readNavigation(storage, "budget", "new", text)?.length, 10_000);
const unavailable = { getItem: () => { throw new Error("denied"); }, setItem: () => { throw new Error("full"); } };
assert.equal(readNavigation(unavailable, "scope", "key", optionalNavigationId), undefined);
assert.doesNotThrow(() => writeNavigation(unavailable, "scope", "key", "target", optionalNavigationId));
assert.equal(parentWhenMissing("target", false, () => false), "target");
assert.equal(parentWhenMissing("target", true, () => false), null);
assert.equal(parentWhenMissing("target", true, () => true), "target");
console.log("viewerNavigation: 16 assertions passed");
