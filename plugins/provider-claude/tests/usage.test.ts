const plugin = module.exports.default;
const raw = plugin.fetchUsage();
const parsed = plugin.parseUsage(raw, 1);
const expected = normalizeClaudeUsage(fixture)!;
assert.deepEqual(JSON.parse(raw), JSON.parse(fs.readFileSync(new URL("./fixtures/usage-normalized.json", import.meta.url), "utf8")));
assert.deepEqual(JSON.parse(JSON.stringify(parsed.usage_details)), expected.usage_details);
assert.equal(parsed.session_pct, 17);
assert.equal(parsed.weekly_pct, 60);
assert.equal(expected.usage_details.limits[2].label, "Weekly · Fable");
assert.equal(expected.usage_details.limits[2].critical, true);
assert.equal(expected.usage_details.limits[2].is_active, true);
assert.equal(expected.usage_details.dollar_credits[0].remaining_dollars, 250);
assert.equal(expected.usage_details.dollar_credits[0].resets_at, Date.parse("2026-11-05T00:00:00Z"));
assert.equal(expected.usage_details.extra_usage?.enabled, false);
assert.equal(raw.includes("opaque-secret"), false);
const {opaque_allowance_29, ...withoutCredit} = fixture;
body = {...withoutCredit, wholly_unknown_key: opaque_allowance_29};
